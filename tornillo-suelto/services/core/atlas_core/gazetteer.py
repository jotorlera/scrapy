@lru_cache(maxsize=1)
def _compiled() -> list[tuple[str, str, str, str | None, str, re.Pattern]]:
    """Lista de (key, kind, name, country, alias_normalizado, regex)."""
    items: list[tuple[str, str, str, str | None, str]] = []
    for c in countries().values():
        for alias in (c.name_es, c.name_en, *c.aliases):
            items.append((f"country:{c.iso2}", "country", c.name_es, c.iso2, alias))
    for kind, name, aliases, country in _INSTITUTIONS:
        for alias in (name, *aliases):
            items.append((f"{kind}:{name}", kind, name, country, alias))
    for name, aliases in _TOPICS:
        for alias in aliases:
            items.append((f"topic:{name}", "topic", name, None, alias))
    out = []
    seen: set[tuple[str, str]] = set()
    for key, kind, name, country, alias in items:
        a = normalize_text(alias.strip())
        if not a or (key, a) in seen:
            continue
        seen.add((key, a))
        # límite de palabra tolerante a puntos ("ee. uu.") y guiones
        rx = re.compile(r"(?<![\w])" + re.escape(a) + r"(?![\w])")
        out.append((key, kind, name, country, a, rx))
    return out


def _case_ok(alias: str, *originals: str) -> bool:
    """Para siglas y apellidos ambiguos: exigir mayúscula inicial o todo mayúsculas en el texto original."""
    variants = {alias.upper(), alias.capitalize(), alias.title()}
    for v in variants:
        rx = re.compile(r"(?<![\w])" + re.escape(v) + r"(?![\w])")
        if any(rx.search(o) for o in originals if o):
            return True
    return False


def find_mentions(text: str, title: str | None = None) -> list[Mention]:
    """Devuelve menciones de entidades con recuento; el título cuenta triple."""
    if not text and not title:
        return []
    body = text or ""
    ttl = title or ""
    norm_body = normalize_text(body)
    norm_title = normalize_text(ttl)
    counts: dict[str, list] = {}
    for key, kind, name, country, alias, rx in _compiled():
        n_body = len(rx.findall(norm_body))
        n_title = len(rx.findall(norm_title))
        if n_body + n_title == 0:
            continue
        if alias in _CASE_SENSITIVE and not _case_ok(alias, body, ttl):
            continue
        entry = counts.setdefault(key, [kind, name, country, 0])
        entry[3] += n_body + 3 * n_title
    out = [Mention(k, v[0], v[1], v[2], v[3]) for k, v in counts.items()]
    out.sort(key=lambda m: -m.count)
    return out


def countries_from_mentions(mentions: list[Mention], max_n: int = 4) -> list[str]:
    """Países principales: explícitos primero; instituciones con país aportan la mitad."""
    score: dict[str, float] = {}
    for m in mentions:
        if m.kind == "country" and m.country:
            score[m.country] = score.get(m.country, 0) + m.count
        elif m.country and m.kind in ("institution", "company"):
            score[m.country] = score.get(m.country, 0) + 0.5 * m.count
    ranked = sorted(score.items(), key=lambda kv: -kv[1])
    if not ranked:
        return []
    top = ranked[0][1]
    return [c for c, s in ranked[:max_n] if s >= max(1.0, 0.2 * top)]


def principal_keys(mentions: list[Mention], max_n: int = 5) -> list[str]:
    """Claves de entidad principales (países + instituciones/empresas, sin temas) para el clustering."""
    keys = [m.key for m in mentions if m.kind in ("country", "institution", "company")]
    return keys[:max_n]


def topics_from_mentions(mentions: list[Mention]) -> list[str]:
    return [m.name for m in mentions if m.kind == "topic"][:4]


