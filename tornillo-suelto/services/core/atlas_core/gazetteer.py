def classify_domain(text: str) -> str:
    t = " " + normalize_text(text) + " "
    best, best_score = "politics", 0
    for domain, kws in DOMAIN_RULES:
        s = 0
        for kw in kws:
            k = normalize_text(kw)
            if k.startswith(" ") or k.endswith(" "):
                s += t.count(k)
            else:
                s += len(re.findall(r"(?<![\w])" + re.escape(k), t))
        if s > best_score:
            best, best_score = domain, s
    return best
